CREATE TABLE IF NOT EXISTS public.fulfilment_locations (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    label TEXT NOT NULL,
    address TEXT NOT NULL,
    latitude DOUBLE PRECISION NOT NULL CHECK (latitude BETWEEN -90 AND 90),
    longitude DOUBLE PRECISION NOT NULL CHECK (longitude BETWEEN -180 AND 180),
    active BOOLEAN NOT NULL DEFAULT true,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.fulfilment_transactions (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    buyer_token_hash TEXT NOT NULL,
    seller_token_hash TEXT NOT NULL,
    buyer_token_ciphertext TEXT NOT NULL,
    seller_token_ciphertext TEXT NOT NULL,
    buyer_name TEXT NOT NULL,
    buyer_phone TEXT NOT NULL,
    seller_phone TEXT NOT NULL,
    seller_name TEXT,
    item_description TEXT,
    item_value NUMERIC(12, 2) CHECK (item_value IS NULL OR item_value > 0),
    insurance_rate_pct NUMERIC(5, 2) NOT NULL,
    insurance_amount NUMERIC(12, 2),
    photo_paths TEXT[] NOT NULL DEFAULT '{}',
    origin JSONB,
    destination JSONB,
    salary_deduction_amount NUMERIC(12, 2),
    salary_deduction_consent_at TIMESTAMPTZ,
    status TEXT NOT NULL DEFAULT 'seller_response_pending' CHECK (status IN (
        'seller_response_pending',
        'buyer_checkout_pending',
        'mfi_review',
        'delivery_pending',
        'in_transit',
        'delivered',
        'return_window',
        'return_requested',
        'settlement_due',
        'completed',
        'returned',
        'cancelled',
        'delivery_exception'
    )),
    shipday_order_id TEXT,
    shipday_tracking_id TEXT,
    shipday_tracking_url TEXT,
    shipday_status TEXT,
    driver_location JSONB,
    picked_up_at TIMESTAMPTZ,
    delivered_at TIMESTAMPTZ,
    parcel_received_at TIMESTAMPTZ,
    return_window_ends_at TIMESTAMPTZ,
    payout_reference TEXT,
    seller_paid_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.fulfilment_loan_requests (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    transaction_id UUID NOT NULL UNIQUE
        REFERENCES public.fulfilment_transactions(id) ON DELETE CASCADE,
    borrower_name TEXT NOT NULL,
    borrower_phone TEXT NOT NULL,
    amount NUMERIC(12, 2) NOT NULL CHECK (amount > 0),
    repayment_method TEXT NOT NULL DEFAULT 'salary_deduction'
        CHECK (repayment_method = 'salary_deduction'),
    status TEXT NOT NULL DEFAULT 'pending_mfi' CHECK (status IN (
        'pending_mfi',
        'approved',
        'rejected',
        'funded',
        'returned'
    )),
    consent_at TIMESTAMPTZ NOT NULL,
    reviewed_at TIMESTAMPTZ,
    reviewed_by UUID REFERENCES auth.users(id) ON DELETE SET NULL,
    review_note TEXT,
    payout_reference TEXT,
    funded_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.fulfilment_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    transaction_id UUID NOT NULL
        REFERENCES public.fulfilment_transactions(id) ON DELETE CASCADE,
    event_type TEXT NOT NULL,
    description TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS fulfilment_transactions_status_idx
    ON public.fulfilment_transactions (status, updated_at DESC);
CREATE INDEX IF NOT EXISTS fulfilment_events_transaction_idx
    ON public.fulfilment_events (transaction_id, created_at);
CREATE INDEX IF NOT EXISTS fulfilment_loan_requests_status_idx
    ON public.fulfilment_loan_requests (status, created_at DESC);
CREATE INDEX IF NOT EXISTS fulfilment_shipday_order_id_idx
    ON public.fulfilment_transactions (shipday_order_id)
    WHERE shipday_order_id IS NOT NULL;

ALTER TABLE public.fulfilment_locations ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.fulfilment_transactions ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.fulfilment_loan_requests ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.fulfilment_events ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Active fulfilment locations are public" ON public.fulfilment_locations;
CREATE POLICY "Active fulfilment locations are public"
    ON public.fulfilment_locations FOR SELECT
    TO anon, authenticated
    USING (active);

DROP POLICY IF EXISTS "MFI operators read fulfilment loan requests" ON public.fulfilment_loan_requests;
CREATE POLICY "MFI operators read fulfilment loan requests"
    ON public.fulfilment_loan_requests FOR SELECT
    TO authenticated
    USING (public.is_sumthin_mfi_operator());

GRANT SELECT ON public.fulfilment_locations TO anon, authenticated;
REVOKE ALL ON public.fulfilment_transactions, public.fulfilment_events FROM anon, authenticated;
REVOKE ALL ON public.fulfilment_loan_requests FROM anon, authenticated;
GRANT SELECT ON public.fulfilment_loan_requests TO authenticated;
GRANT ALL ON public.fulfilment_locations, public.fulfilment_transactions,
    public.fulfilment_loan_requests, public.fulfilment_events TO service_role;

